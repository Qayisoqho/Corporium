const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const context=vm.createContext({document:{documentElement:{classList:{toggle(){}}}},localStorage:{getItem(){return null}}});
vm.runInContext(`const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); const activeLanguage='a';const languageList=[{id:'a',metadata:JSON.stringify({glossary:{GEN:'属格',GENITIVE:'属格',SG:'单数','3':'第三人称'}})},{id:'b',metadata:'{}'}];`,context);
vm.runInContext(fs.readFileSync('web/display-tools.js','utf8'),context);
const render=(s,l='a')=>context.richGloss(s,l);
assert.equal((render('dog-gen.3sg') .match(/grammar-label/g)||[]).length,3);
assert.equal(render('genesis'),'genesis');
assert.equal(render('dog-gen','b'),'dog-gen');
assert.equal(render('GENITIVE'),'<span class="grammar-label" title="属格">GENITIVE</span>');
assert.equal(render('#sub[GEN]'),'<sub><span class="grammar-label" title="属格">GEN</span></sub>');
assert.ok(!render('<img src=x onerror=bad>').includes('<img'));
assert.equal(context.lexemePlainLabel({headword:'bank',body:{homonym_number:12}}),'bank₁₂');
console.log('Display tokenization and homonym label checks passed.');
assert.ok(render('s.1>o.3sg').includes('class="gloss-relation"'));
assert.ok(render('s.1>o.3sg').includes('&gt;'));
assert.equal(context.phonologicalBoundary('###'),true);
assert.equal(context.phonologicalBoundary('#sub[x]'),false);
assert.equal(context.phonologicalBoundary('x#'),false);
for(const sep of ['.', ';', ':', '\\'])assert.equal((render('dog'+sep+'GEN'+sep+'SG').match(/grammar-label/g)||[]).length,2);
assert.ok(render('son[nom.sg]','b').includes('son<span class="gloss-bracket">['));
assert.equal((render('son[nom.sg]','b').match(/grammar-label/g)||[]).length,0);
assert.equal(JSON.stringify(context.glossEditParts('son[nom.sg]-PL')),JSON.stringify(['son[nom.sg]','-','PL']));
assert.equal(JSON.stringify(context.glossEditParts('son[nom+sg]')),JSON.stringify(['son[nom+sg]']));
assert.equal(JSON.stringify(context.glossEditParts('son;nom:sg_acc\\pl')),JSON.stringify(['son',';','nom',':','sg_acc','\\','pl']));
assert.equal(context.boundaryGloss({form:'##',gloss:'boundary'},'a'),'');
assert.ok(render('home<nom.pl><emph>').includes('class="gloss-infix"'));
assert.ok(!render('home<nom.pl>').includes('class="gloss-relation"'));
assert.equal((render('home<s.1>o.3sg>').match(/class="gloss-relation"/g)||[]).length,1);
assert.equal(JSON.stringify(context.glossEditParts('home<nom.pl><emph>-PL')),JSON.stringify(['home<nom.pl><emph>','-','PL']));
assert.equal(JSON.stringify(context.glossEditParts('so<l><u>ma-x',false)),JSON.stringify(['so<l><u>ma','-','x']));
